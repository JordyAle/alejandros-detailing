const menuButton = document.querySelector('.menu-toggle');
const mainMenu = document.querySelector('.main-menu');
const header = document.querySelector('.site-header');
const languageButton = document.querySelector('.language-toggle');
const modal = document.querySelector('.image-modal');
const modalImage = modal.querySelector('img');
const closeModalButton = modal.querySelector('.modal-close');
let currentLanguage = localStorage.getItem('alejandros-language') === 'en' ? 'en' : 'es';

function whatsappUrl(message) {
  return `https://wa.me/${WHATSAPP_NUMBER}?text=${encodeURIComponent(message)}`;
}

function generalMessage() {
  if (currentLanguage === 'en') {
    return "Hello Alejandro's Detailing! 👋\nI would like information about your mobile detailing packages.\n\n📍 My area is: ____\n🚘 My vehicle is: ____\n🕐 Preferred date/time: ____";
  }
  return "Hola Alejandro's Detailing 👋\nQuiero información sobre sus paquetes de detallado a domicilio.\n\n📍 Mi zona es: ____\n🚘 Mi vehículo es: ____\n🕐 Fecha y hora preferida: ____";
}

function packageMessage(option) {
  const service = option.dataset[`service${currentLanguage === 'es' ? 'Es' : 'En'}`];
  const vehicle = option.dataset[`vehicle${currentLanguage === 'es' ? 'Es' : 'En'}`];
  const price = Number(option.dataset.price).toLocaleString('en-US');

  if (currentLanguage === 'en') {
    return `Hello Alejandro's Detailing! 👋\nI would like to request this package:\n\n🚘 Service: ${service}\n📦 Vehicle: ${vehicle}\n💵 Starting price: $${price} USD\n📍 Service area: Orange County / Los Angeles\n🏠 24/7 mobile service\n\nDo you have availability?\nMy exact location is: ____\nPreferred date/time: ____`;
  }

  return `Hola Alejandro's Detailing 👋\nQuiero solicitar este paquete:\n\n🚘 Servicio: ${service}\n📦 Vehículo: ${vehicle}\n💵 Precio desde: $${price} USD\n📍 Zona: Orange County / Los Angeles\n🏠 Servicio móvil a domicilio 24/7\n\n¿Tienen disponibilidad?\nMi ubicación exacta es: ____\nFecha y hora preferida: ____`;
}

function updateLanguage(language) {
  currentLanguage = language;
  localStorage.setItem('alejandros-language', language);
  document.documentElement.lang = language;

  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const value = translations[language][element.dataset.i18n];
    if (value) element.textContent = value;
  });

  document.querySelectorAll('[data-i18n-html]').forEach((element) => {
    const value = translations[language][element.dataset.i18nHtml];
    if (value) element.innerHTML = value;
  });

  document.querySelectorAll('[data-lang-option]').forEach((option) => {
    option.classList.toggle('active', option.dataset.langOption === language);
  });

  document.querySelectorAll('.package-option').forEach((option) => {
    const key = language === 'es' ? 'vehicleEs' : 'vehicleEn';
    option.querySelector('.vehicle-name').textContent = option.dataset[key];
    option.querySelector('.select-label').textContent = translations[language].selectLabel;
  });

  const heroFlyer = document.querySelector('#hero-flyer');
  heroFlyer.src = heroFlyer.dataset[language];

  document.querySelectorAll('.gallery-item').forEach((item) => {
    item.querySelector('img').src = item.dataset[language];
  });

  document.querySelectorAll('.whatsapp-general').forEach((link) => {
    link.href = whatsappUrl(generalMessage());
    link.target = '_blank';
    link.rel = 'noopener noreferrer';
  });
}

menuButton.addEventListener('click', () => {
  const open = mainMenu.classList.toggle('open');
  menuButton.setAttribute('aria-expanded', String(open));
});

mainMenu.querySelectorAll('a').forEach((link) => {
  link.addEventListener('click', () => {
    mainMenu.classList.remove('open');
    menuButton.setAttribute('aria-expanded', 'false');
  });
});

languageButton.addEventListener('click', () => {
  updateLanguage(currentLanguage === 'es' ? 'en' : 'es');
});

document.querySelectorAll('.package-option').forEach((option) => {
  option.addEventListener('click', () => {
    window.open(whatsappUrl(packageMessage(option)), '_blank', 'noopener,noreferrer');
  });
});

document.querySelectorAll('.image-trigger').forEach((trigger) => {
  trigger.addEventListener('click', () => {
    modalImage.src = trigger.dataset[currentLanguage];
    modalImage.alt = translations[currentLanguage].modalAlt;
    document.body.classList.add('modal-open');
    modal.showModal();
  });
});

function closeModal() {
  if (!modal.open) return;
  modal.close();
  document.body.classList.remove('modal-open');
  modalImage.src = '';
}

closeModalButton.addEventListener('click', closeModal);
modal.addEventListener('click', (event) => {
  const bounds = modal.getBoundingClientRect();
  const outside = event.clientX < bounds.left || event.clientX > bounds.right || event.clientY < bounds.top || event.clientY > bounds.bottom;
  if (outside) closeModal();
});
modal.addEventListener('close', () => document.body.classList.remove('modal-open'));

window.addEventListener('scroll', () => {
  header.classList.toggle('scrolled', window.scrollY > 12);
}, { passive: true });

document.querySelector('#year').textContent = new Date().getFullYear();
updateLanguage(currentLanguage);
